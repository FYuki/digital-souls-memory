def upgrade() -> None:
    op.execute("""
        CREATE TABLE sessions (
            session_id TEXT PRIMARY KEY CHECK (session_id ~ '\\S'),
            started_at TIMESTAMPTZ NOT NULL,
            ended_at TIMESTAMPTZ,
            surface TEXT NOT NULL CHECK (surface ~ '\\S'),
            participants TEXT[] NOT NULL
        )
    """)
    op.execute("""
        CREATE TABLE turns (
            turn_id TEXT PRIMARY KEY CHECK (turn_id ~ '\\S'),
            session_id TEXT NOT NULL REFERENCES sessions(session_id),
            surface TEXT NOT NULL CHECK (surface ~ '\\S'),
            actor TEXT NOT NULL CHECK (actor ~ '\\S'),
            kind TEXT NOT NULL CHECK (kind IN ('utterance', 'observation')),
            text TEXT NOT NULL,
            audience TEXT[] NOT NULL,
            language TEXT NOT NULL CHECK (language ~ '\\S'),
            register JSONB NOT NULL CHECK (jsonb_typeof(register) = 'object'),
            sensitivity TEXT NOT NULL CHECK (sensitivity ~ '\\S'),
            classifier_version TEXT NOT NULL CHECK (classifier_version ~ '\\S'),
            occurred_at TIMESTAMPTZ NOT NULL,
            recorded_at TIMESTAMPTZ NOT NULL
        )
    """)
    op.execute("""
        CREATE TABLE delivery_receipts (
            receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            turn_id TEXT NOT NULL REFERENCES turns(turn_id),
            status TEXT NOT NULL CHECK (status IN ('full', 'partial', 'none')),
            spoken_until BIGINT NOT NULL CHECK (spoken_until >= 0),
            reported_by TEXT NOT NULL CHECK (reported_by ~ '\\S'),
            reported_at TIMESTAMPTZ NOT NULL
        )
    """)
    op.execute("""
        CREATE FUNCTION reject_evidence_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            RAISE EXCEPTION 'Evidence is append-only' USING ERRCODE = '42501';
        END;
        $$
    """)
    for table in ("sessions", "turns", "delivery_receipts"):
        op.execute(
            f"CREATE TRIGGER evidence_immutable BEFORE UPDATE OR DELETE ON {table} "
            "FOR EACH ROW EXECUTE FUNCTION reject_evidence_mutation()"
        )
    op.execute("""
        CREATE FUNCTION validate_delivery_range() RETURNS trigger LANGUAGE plpgsql AS $$
        DECLARE text_length INTEGER;
        BEGIN
            SELECT char_length(text) INTO text_length FROM turns WHERE turn_id = NEW.turn_id;
            IF (NEW.status = 'full' AND NEW.spoken_until <> text_length)
                OR (NEW.status = 'partial' AND NOT (NEW.spoken_until > 0
                    AND NEW.spoken_until < text_length))
                OR (NEW.status = 'none' AND NEW.spoken_until <> 0) THEN
                RAISE EXCEPTION 'Invalid delivery range' USING ERRCODE = '23514';
            END IF;
            RETURN NEW;
        END;
        $$
    """)
    op.execute("""
        CREATE TRIGGER delivery_range BEFORE INSERT ON delivery_receipts
        FOR EACH ROW EXECUTE FUNCTION validate_delivery_range()
    """)


